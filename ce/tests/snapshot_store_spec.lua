package.path='ce/modules/?.lua;'..package.path
local S=require('snapshot')
local Store=require('snapshotstore')
local tests=0
local function test(name,fn)
  local ok,err=pcall(fn)
  if not ok then error(name..': '..tostring(err)) end
  tests=tests+1
  print('PASS '..name)
end
local function eq(a,b,label) assert(a==b,(label or 'value')..': expected '..tostring(b)..' got '..tostring(a)) end
local function read(path) local f=assert(io.open(path,'rb'));local t=f:read('*a');f:close();return t end
local function write(path,text) local f=assert(io.open(path,'wb'));f:write(text);f:close() end
local function tempPath(suffix)
  local p=os.tmpname()
  os.remove(p)
  return p..(suffix or '.json')
end
local function validSnapshot()
  local s=assert(S.decode(read('ce/tests/fixtures/corpus/snapshots/ffrs-reference.json')))
  return s
end
local function cleanup(path)
  os.remove(path);os.remove(path..Store.PARTIAL_SUFFIX);os.remove(path..Store.BACKUP_SUFFIX)
end

test('new file write/read roundtrip is semantically identical',function()
  local path=tempPath();local s=validSnapshot()
  local result,err=Store.write(s,path,{overwrite=false})
  assert(result,err and err.message)
  local got,readErr=Store.read(path)
  assert(got,readErr and readErr.message)
  eq(got.snapshot_id,s.snapshot_id)
  eq(S.encode(got),S.encode(s))
  local d=S.compare(s,got)
  eq(d.comparability.status,'comparable')
  eq(d.candidates.unchanged,#s.candidates)
  eq(io.open(path..Store.PARTIAL_SUFFIX,'rb'),nil)
  eq(io.open(path..Store.BACKUP_SUFFIX,'rb'),nil)
  cleanup(path)
end)

test('overwrite cancelled preserves existing bytes',function()
  local path=tempPath();local s=validSnapshot()
  assert(Store.write(s,path,{}))
  local before=read(path)
  local result,err=Store.write(s,path,{overwrite=false})
  eq(result,nil);eq(err.code,'overwrite_required')
  eq(read(path),before)
  cleanup(path)
end)

test('overwrite accepted replaces atomically',function()
  local path=tempPath();local s=validSnapshot()
  assert(Store.write(s,path,{}))
  local s2=validSnapshot();s2.created_at='2026-10-27T00:00:00Z';s2.snapshot_id=S.normalize(s2).snapshot_id
  local result,err=Store.write(s2,path,{overwrite=true})
  assert(result,err and err.message)
  local got=assert(Store.read(path))
  eq(got.snapshot_id,s2.snapshot_id)
  cleanup(path)
end)

test('reserved temporary file fails closed and preserves original',function()
  local path=tempPath();local s=validSnapshot()
  assert(Store.write(s,path,{}))
  local before=read(path)
  write(path..Store.PARTIAL_SUFFIX,'reserved')
  local result,err=Store.write(s,path,{overwrite=true})
  eq(result,nil);eq(err.code,'temp_exists')
  eq(read(path),before)
  cleanup(path)
end)

test('write failure does not leave a final file or partial',function()
  local dir=tempPath('.dir')
  os.execute('mkdir "'..dir..'"')
  local s=validSnapshot()
  local result,err=Store.write(s,dir,{overwrite=true})
  eq(result,nil);assert(err and err.code)
  eq(io.open(dir..Store.PARTIAL_SUFFIX,'rb'),nil)
  os.execute('rmdir "'..dir..'"')
  cleanup(dir)
end)

test('oversized file is rejected before decode',function()
  local path=tempPath();local f=assert(io.open(path,'wb'))
  f:write(string.rep('x',Store.MAX_BYTES+1));f:close()
  local s,err=Store.read(path)
  eq(s,nil);eq(err.code,'snapshot_too_large')
  cleanup(path)
end)

test('invalid and truncated JSON fail with stable codes',function()
  local path=tempPath()
  write(path,'not json')
  local s,e=Store.read(path);eq(s,nil);eq(e.code,'invalid_json')
  write(path,'{"snapshot_version":')
  s,e=Store.read(path);eq(s,nil);eq(e.code,'truncated_file')
  cleanup(path)
end)

test('wrong version, missing field and wrong type fail closed',function()
  local path=tempPath();local text=S.encode(validSnapshot())
  write(path,text:gsub('"snapshot_version":1','"snapshot_version":2',1))
  local s,e=Store.read(path);eq(s,nil);eq(e.code,'unsupported_snapshot_version')
  write(path,'{}')
  s,e=Store.read(path);eq(s,nil);eq(e.code,'schema_invalid')
  write(path,'{"snapshot_version":"1"}')
  s,e=Store.read(path);eq(s,nil);eq(e.code,'schema_invalid')
  cleanup(path)
end)

test('extra property and corrupted identity fail closed',function()
  local path=tempPath();local text=S.encode(validSnapshot())
  write(path,text:gsub('}$',',"extra":1}',1))
  local s,e=Store.read(path);eq(s,nil);eq(e.code,'schema_invalid')
  local corrupt=text:gsub('"snapshot_id":"snap%-%x+"','"snapshot_id":"snap-00000000000000000000000000000000"',1)
  write(path,corrupt)
  s,e=Store.read(path);eq(s,nil);eq(e.code,'identity_invalid')
  cleanup(path)
end)

print(string.format('%d snapshot storage tests passed',tests))
