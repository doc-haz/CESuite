"""Deterministic, dependency-free CT/Lua packaging; never executes table code."""
from pathlib import Path
import argparse
import re
import zipfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def version():
    return re.search(r"version='(\d+\.\d+\.\d+(?:\.\d+)?)'", (ROOT / 'ce/CESuite_Core.lua').read_text(encoding='utf-8')).group(1)


def bundle():
    parts = [f'-- CESuite Core Runtime {version()}; generated by tools/build_ce.py',
             'local factories, loaded = {}, {}']
    for path in sorted((ROOT / 'ce/modules').glob('*.lua')):
        parts.append(f"factories['{path.stem}'] = function(require, api)\n{path.read_text(encoding='utf-8')}\nend")
    parts.append('''local api = _G
local function requireModule(name)
  if loaded[name] then return loaded[name] end
  assert(factories[name], 'Unknown CESuite module: '..name)
  loaded[name] = factories[name](requireModule, api)
  return loaded[name]
end
local function entry(require, api)
''')
    parts.append((ROOT / 'ce/CESuite_Core.lua').read_text(encoding='utf-8'))
    parts.append(f"end\nlocal version='{version()}'\nlocal mode='portable'\nlocal function factory() return entry(requireModule,api) end")
    parts.append((ROOT / 'ce/bootstrap.lua').read_text(encoding='utf-8'))
    return '\n'.join(parts)


def autorun_files():
    files = {'CESuite_Autorun.lua': (ROOT / 'ce/CESuite_Autorun.lua').read_text(encoding='utf-8').replace('@VERSION@', version()),
             'cesuite/core.lua': (ROOT / 'ce/CESuite_Core.lua').read_text(encoding='utf-8'),
             'cesuite/bootstrap.lua': (ROOT / 'ce/bootstrap.lua').read_text(encoding='utf-8')}
    for path in sorted((ROOT / 'ce/modules').glob('*.lua')):
        files['cesuite/' + path.name] = path.read_text(encoding='utf-8')
    return files


def build(destination):
    destination.mkdir(parents=True, exist_ok=True)
    source = bundle()
    root = ET.Element('CheatTable', CheatEngineTableVersion='45')
    ET.SubElement(root, 'CheatEntries')
    ET.SubElement(root, 'UserdefinedSymbols')
    ET.SubElement(root, 'LuaScript').text = source
    ET.indent(root, space='  ')
    ct = ET.tostring(root, encoding='utf-8', xml_declaration=True) + b'\n'
    for name in ['CESuite_Core.CT', f'CESuite_Core_v{version()}.CT']:
        (destination / name).write_bytes(ct)
    (destination / 'CESuite_Core.lua').write_text(source, encoding='utf-8', newline='\n')
    # Fixed metadata and stored compression give byte-reproducible ZIPs.
    with zipfile.ZipFile(destination / f'CESuite_Autorun_v{version()}.zip', 'w') as archive:
        for name, text in sorted(autorun_files().items()):
            info = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, text.encode('utf-8'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'releases')
    build(parser.parse_args().output)
